// Builds supabase/migrations/20261015000400_seed_food_items.sql from supabase/seed/food_items.csv.
// Usage: npm run seed:build   (re-run after editing the CSV, then commit both files)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const CSV_PATH = join(root, 'supabase', 'seed', 'food_items.csv');
const OUT = join(root, 'supabase', 'migrations', '20261015000400_seed_food_items.sql');

const UNITS = ['katori', 'roti', 'piece', 'plate', 'scoop', 'glass', 'tbsp', 'g'];
const num = (s) => (s === '' || s === undefined ? null : Number(s));

/** Parses the seed CSV (no quoted fields; '#' lines are comments) into food_items rows. */
export function parseSeed(text = readFileSync(CSV_PATH, 'utf8')) {
  const lines = text.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith('#'));
  const header = lines.shift().split(',');
  return lines.map((line, i) => {
    const cells = line.split(',');
    if (cells.length !== header.length)
      throw new Error(`row ${i + 2}: expected ${header.length} cells, got ${cells.length}`);
    const r = Object.fromEntries(header.map((h, j) => [h, cells[j].trim()]));
    const units = { default: r.unit };
    for (const pair of r.unit_grams ? r.unit_grams.split('|') : []) {
      const [u, g] = pair.split(':');
      units[u] = Number(g);
    }
    const protein = num(r.protein);
    const carbs = num(r.carbs);
    const fat = num(r.fat);
    return {
      slug: r.slug,
      name: r.name,
      aliases: r.aliases
        ? r.aliases
            .split('|')
            .map((a) => a.trim())
            .filter(Boolean)
        : [],
      cuisine: r.cuisine || null,
      region: r.region || null,
      kind: r.kind,
      units,
      density_g_per_ml: num(r.density),
      // Atwater factors; values are authored macros, so kcal always agrees with them.
      kcal_100g: Math.round((4 * protein + 4 * carbs + 9 * fat) * 10) / 10,
      protein_100g: protein,
      carbs_100g: carbs,
      fat_100g: fat,
      default_oil_g: num(r.oil_g) ?? 0,
      source: 'recipe',
      is_verified: false,
      unitsValid: UNITS.includes(r.unit) && Object.keys(units).every((u) => u === 'default' || UNITS.includes(u)),
    };
  });
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

export function toSql(rows) {
  const values = rows.map(
    (r) =>
      `  (${q(r.slug)}, ${q(r.name)}, ${arr(r.aliases)}, ${q(r.cuisine)}, ${q(r.region)}, ${q(r.kind)}, ${q(JSON.stringify(r.units))}::jsonb, ${r.density_g_per_ml ?? 'null'}, ${r.kcal_100g}, ${r.protein_100g}, ${r.carbs_100g}, ${r.fat_100g}, ${r.default_oil_g}, ${q(r.source)}, ${r.is_verified})`,
  );
  return `-- GENERATED by scripts/build-seed.mjs from supabase/seed/food_items.csv. Do not edit by hand.
-- Authored approximations (source=recipe, is_verified=false); see the CSV header.
insert into public.food_items
  (slug, name, aliases, cuisine, region, kind, units, density_g_per_ml, kcal_100g, protein_100g, carbs_100g, fat_100g, default_oil_g, source, is_verified)
values
${values.join(',\n')}
on conflict (slug) do update set
  name = excluded.name, aliases = excluded.aliases, cuisine = excluded.cuisine, region = excluded.region,
  kind = excluded.kind, units = excluded.units, density_g_per_ml = excluded.density_g_per_ml,
  kcal_100g = excluded.kcal_100g, protein_100g = excluded.protein_100g, carbs_100g = excluded.carbs_100g,
  fat_100g = excluded.fat_100g, default_oil_g = excluded.default_oil_g, source = excluded.source,
  is_verified = excluded.is_verified;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rows = parseSeed();
  writeFileSync(OUT, toSql(rows));
  console.log(`wrote ${rows.length} food_items (${rows.filter((r) => r.kind === 'dish').length} dishes) to ${OUT}`);
}
