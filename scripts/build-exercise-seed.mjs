// Builds supabase/migrations/20261016000200_seed_exercises.sql (exercise library + library templates) and the
// demo copy src/features/demo/exercises.json from supabase/seed/exercises.json (free-exercise-db, Unlicense)
// plus supabase/seed/exercise_extras.json (Katori aliases + templates).
// Usage: npm run seed:exercises
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'supabase', 'migrations', '20261016000200_seed_exercises.sql');
const DEMO_OUT = join(root, 'src', 'features', 'demo', 'exercises.json');

const EQUIPMENT = {
  'body only': 'body_only',
  'e-z curl bar': 'ez_bar',
  'medicine ball': 'medicine_ball',
  'exercise ball': 'exercise_ball',
  'foam roll': 'foam_roll',
};
const CATEGORY = { 'olympic weightlifting': 'olympic_weightlifting' };

/** Dataset + extras → rows in our schema's vocabulary. */
export function loadExercises() {
  const data = JSON.parse(readFileSync(join(root, 'supabase', 'seed', 'exercises.json'), 'utf8'));
  const extras = JSON.parse(readFileSync(join(root, 'supabase', 'seed', 'exercise_extras.json'), 'utf8'));
  const rows = data.map((e) => ({
    slug: e.id,
    name: e.name,
    aliases: extras.aliases[e.id] ?? [],
    primary_muscles: e.primaryMuscles ?? [],
    secondary_muscles: e.secondaryMuscles ?? [],
    equipment: e.equipment ? (EQUIPMENT[e.equipment] ?? e.equipment) : null,
    mechanic: e.mechanic ?? null,
    force: e.force ?? null,
    level: e.level ?? null,
    category: CATEGORY[e.category] ?? e.category,
    instructions: e.instructions ?? [],
    images: e.images ?? [],
  }));
  return { rows, extras };
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;

function toSql({ rows, extras }) {
  const values = rows.map(
    (r) =>
      `  (${q(r.slug)}, ${q(r.name)}, ${arr(r.aliases)}, ${arr(r.primary_muscles)}, ${arr(r.secondary_muscles)}, ${q(r.equipment)}, ${q(r.mechanic)}, ${q(r.force)}, ${q(r.level)}, ${q(r.category)}, ${arr(r.instructions)}, ${arr(r.images)}, 'free-exercise-db')`,
  );
  const templates = extras.templates.map(
    (t, i) => `  (${q(t.id)}, null, ${q(t.name)}, ${q(t.split)}, ${q(t.notes)}, ${i})`,
  );
  const items = extras.templates.flatMap((t) =>
    t.exercises.map(
      ([slug, sets, min, max, rest], pos) =>
        `insert into public.template_exercises (template_id, position, exercise_id, sets, rep_min, rep_max, rest_s)\n  select ${q(t.id)}, ${pos}, e.id, ${sets}, ${min}, ${max}, ${rest} from public.exercises e where e.slug = ${q(slug)};`,
    ),
  );
  return `-- GENERATED by scripts/build-exercise-seed.mjs. Do not edit by hand.
-- Exercise library from free-exercise-db (Unlicense, https://github.com/yuhonas/free-exercise-db) plus Katori
-- aliases and library templates (supabase/seed/exercise_extras.json). images[] are paths relative to the image base.
insert into public.exercises
  (slug, name, aliases, primary_muscles, secondary_muscles, equipment, mechanic, force, level, category, instructions, images, source)
values
${values.join(',\n')}
on conflict (slug) do update set
  name = excluded.name, aliases = excluded.aliases, primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles, equipment = excluded.equipment, mechanic = excluded.mechanic,
  force = excluded.force, level = excluded.level, category = excluded.category,
  instructions = excluded.instructions, images = excluded.images;

insert into public.workout_templates (id, owner_id, name, split, notes, position)
values
${templates.join(',\n')}
on conflict (id) do update set name = excluded.name, split = excluded.split, notes = excluded.notes, position = excluded.position;

delete from public.template_exercises where template_id in (${extras.templates.map((t) => q(t.id)).join(', ')});
${items.join('\n')}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const seed = loadExercises();
  const slugs = new Set(seed.rows.map((r) => r.slug));
  for (const id of Object.keys(seed.extras.aliases))
    if (!slugs.has(id)) throw new Error(`alias for unknown exercise ${id}`);
  for (const t of seed.extras.templates)
    for (const [slug] of t.exercises)
      if (!slugs.has(slug)) throw new Error(`template ${t.name}: unknown exercise ${slug}`);
  writeFileSync(OUT, toSql(seed));
  const demo = seed.rows.map(({ force, level, ...r }, i) => ({
    id: `00000000-0000-4000-9000-${String(i + 1).padStart(12, '0')}`,
    ...r,
    source: 'free-exercise-db',
    owner_id: null,
  }));
  writeFileSync(DEMO_OUT, JSON.stringify({ exercises: demo, templates: seed.extras.templates }));
  console.log(`wrote ${seed.rows.length} exercises and ${seed.extras.templates.length} templates`);
}
