// Copies every `// server-shared` file under src/ into supabase/functions/_shared/gen/, keeping the
// relative layout, so Edge Functions import them from inside the functions folder (the deploy bundler
// only reliably ships files under supabase/functions). tests/shared-sync.test.ts fails if a copy is stale.
// Usage: npm run shared:sync
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src');
export const GEN = join(root, 'supabase', 'functions', '_shared', 'gen');
const ZOD = `npm:zod@${JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).dependencies.zod.replace(/^[^\d]*/, '')}`;
const HEADER = '// GENERATED by scripts/sync-shared.mjs from src/. Edit the source, then run `npm run shared:sync`.\n';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.ts') ? [p] : [];
  });
}

/** Map of gen-relative path → expected file content. */
export function expectedFiles() {
  const out = new Map();
  for (const file of walk(SRC)) {
    const text = readFileSync(file, 'utf8');
    if (!text.startsWith('// server-shared')) continue;
    // Deno has no import map here, so pin zod to the app's version inline.
    out.set(relative(SRC, file).replaceAll('\\', '/'), HEADER + text.replaceAll("from 'zod'", `from '${ZOD}'`));
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  rmSync(GEN, { recursive: true, force: true });
  const files = expectedFiles();
  for (const [rel, content] of files) {
    const target = join(GEN, rel);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  console.log(`synced ${files.size} server-shared files to ${relative(root, GEN)}`);
}
