const useLocaleStore = create<{ locale: Locale }>(() => ({ locale: 'en' }));

export const setLocale = (locale: Locale) => useLocaleStore.setState({ locale });
export const getLocale = () => useLocaleStore.getState().locale;
/** Subscribe a screen to language changes. */
export const useLocale = () => useLocaleStore((s) => s.locale);

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let s: string = (getLocale() === 'hinglish' && hinglish[key]) || en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
